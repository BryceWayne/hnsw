// func hasF16C() bool
// Checks CPUID leaf 1, ECX bit 29 (F16C).
TEXT ·hasF16C(SB), NOSPLIT, $0-1
	MOVL	$1, AX
	XORL	CX, CX
	CPUID
	SHRL	$29, CX
	ANDL	$1, CX
	MOVB	CL, ret+0(FP)
	RET
